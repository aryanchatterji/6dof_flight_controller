# 1. MDO PIPELINE INITIALIZATION

class MDOPipelineEnvironment:
    def __init__(self, config_file="gains_config.json"):
        self.config_file = config_file
        self.system_converged = False
        self.max_coupling_iterations = 150
        self.convergence_tolerance = 1e-5

    def ingest_optimal_gains(self):
        """
        Parses the JSON payload generated by the PSO tuner to instantiate 
        the baseline control parameters for the structural bridge.
        """
        with open(self.config_file, 'r') as file:
            data = json.load(file)
        return data['attitude_controller_gains']


